# границей слова слева и учитывает отрицание ("не битый", "не крашен" —
# частая фраза продавцов, НЕ повод для отказа): см. find_red_flag() в
# monitor.py.
#
# 2026-09-18: где безопасно, используем корень слова вместо точной
# словоформы, чтобы ловить разные грамматические формы — реальный случай:
# "дно и пороги гнилые" не поймалось словом "гнилой". Корень "бит" не ловит
