# 2026-09-16: проверили на реальной выборке (300 объявлений) — "хорошая
# цена" оказалась не редкой (~10% объявлений, 29 из 299), это не "выгодная
# находка", а скорее "нормальная, без переплаты". Взяли только "отличная
# цена" (~1.3%, 4 из 299) — держит канал избирательным. Можно расширить до
# {"отличная цена", "хорошая цена"}, если захочется больше постов ценой
# менее строгого отбора.
GOOD_PRICE_RATINGS = {"отличная цена"}

# Жёсткое вето: если Drom считает цену завышенной — не публикуем, даже если
