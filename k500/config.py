"""
Конфигурация. Секреты (токен бота, id канала) берутся из .env — см. .env.example.
Остальное можно менять прямо здесь.

Это копия проекта drom-underpriced-cars под другой диапазон цен и канал
(@avto500k, 50 000-500 000 ₽) — та же логика и те же фильтры, отдельные
данные (data/) и отдельный launchd job, чтобы не смешивать историю цен и
дедуп публикаций с основным каналом @avito_vrn.
"""
import os
from dotenv import load_dotenv

load_dotenv()

# --- Telegram ---
TELEGRAM_BOT_TOKEN = os.environ.get("TELEGRAM_BOT_TOKEN", "")
TELEGRAM_CHAT_ID = os.environ.get("TELEGRAM_CHAT_ID", "")

# --- Регион и фильтр по цене (Drom.ru) ---
# Подтверждено вручную в браузере 2026-09-16: страница 1 живёт на
# auto.drom.ru/{город}/all/, а страницы N>1 — на
# auto.drom.ru/{город}/all/page{N}/ (домен и путь меняются, не просто ?page=).
DROM_CITY_SLUG = "voronezh"
PRICE_MIN = 50_000
PRICE_MAX = 500_000

DROM_SEARCH_URL_OVERRIDE = None  # например: "https://auto.drom.ru/voronezh/all/?minprice=50000&maxprice=500000"

# --- Логика "цена ниже рынка" ---
# Группируем объявления по (марка, модель, год выпуска).
MIN_SAMPLES_FOR_MEDIAN = 5       # пока в группе меньше наблюдений — не публикуем по своей медиане (см. GOOD_PRICE_RATINGS ниже для более быстрого сигнала)
UNDERPRICED_THRESHOLD = 0.85     # публикуем, если цена <= 85% от медианы группы
PRICE_HISTORY_WINDOW_DAYS = 45   # старые наблюдения дальше этого окна не учитываются в медиане

# Собственная метка Drom о адекватности цены (видна на карточке в поиске) —
# используем как дополнительный сигнал, не дожидаясь накопления своей
# медианы: Drom считает её по намного большей базе объявлений, чем мы можем
# собрать сами. Подтверждённые метки: "отличная цена", "хорошая цена",
# "низкая цена", "нормальная цена", "высокая цена", "завышенная цена".
# Взяли только "отличная цена" (~1.3% объявлений на выборке для основного
# канала) — держит канал избирательным. Можно расширить до
# {"отличная цена", "хорошая цена"}, если захочется больше постов ценой
# менее строгого отбора.
GOOD_PRICE_RATINGS = {"отличная цена"}

# Жёсткое вето: если Drom считает цену завышенной — не публикуем, даже если
# наша собственная (более узкая и не знающая про пробег/владельцев/состояние)
# медиана посчитала иначе (см. историю в README основного проекта — реальный
# случай на канале @avito_vrn).
BAD_PRICE_RATINGS = {"высокая цена", "завышенная цена"}

# --- Проверка на пригодность для перепродажи ---
# Пробег, число владельцев и текст описания не видны на карточке в поиске —
# только на странице самого объявления. Поэтому эти проверки выполняются
# отдельным шагом, только для уже отобранных по цене кандидатов (см.
# enrich_and_filter_for_resale в monitor.py), а не для всех объявлений сразу.

# Сколько владельцев по ПТС ещё приемлемо для перепродажи. Чем больше
# владельцев, тем ниже доверие и труднее продать дальше. Для этого канала
# (50 000-500 000 ₽) порог 2 (как на основном канале 500к-1.5М) отсеивал
# почти все кандидаты — в этом бюджете машины старше и чаще меняли хозяев,
# это норма сегмента, а не тревожный признак. Ослабили до 4.
MAX_OWNERS_FOR_RESALE = 4

# Слова/фразы в описании, намекающие на проблемы с состоянием — плохо для
# перепродажи, даже если цена и число владельцев в порядке. Поиск ищет с
# границей слова слева и учитывает отрицание ("не битый", "не крашен" —
# частая фраза продавцов, НЕ повод для отказа): см. find_red_flag() в
# monitor.py.
#
# 2026-09-18: где безопасно, используем корень слова вместо точной
# словоформы, чтобы ловить разные грамматические формы — реальный случай:
# "дно и пороги гнилые" не поймалось словом "гнилой". Корень "бит" не ловит
# "разбит" (разные словообразования), поэтому это отдельная запись.
RED_FLAG_KEYWORDS = (
    "требует ремонта",
    "нужен ремонт",
    "не на ходу",
    "после дтп",
    "в дтп",
    "авари",       # авария, аварии, аварийный, аварийная, аварийное
    "бит",         # битый, битая, битое, биты (не ловит "разбит" — см. ниже)
    "разбит",      # разбит, разбитый, разбитая, разбитое
    "гнил",        # гнилой, гнилая, гнилые, гниль
    "капремонт",
    "капитальный ремонт",
    "залог",
    "заложен",
    "арест",       # под арестом, арестован, арестованный
    "не подлежит восстановлению",
    "на запчасти",
    "проблемы с документами",
)

# --- Автоудаление старых постов из канала ---
# Через столько дней после публикации сообщение удаляется из канала —
# объявление, скорее всего, уже неактуально (продано/цена изменилась).
# ad_id при этом остаётся в posted.json навсегда, чтобы то же объявление не
# опубликовалось повторно — удаляется только сообщение в Telegram.
POST_TTL_DAYS = 3

# --- Тизер-канал для перекупов (2026-09-18) ---
# Те же находки (обычная публикация — от 15% ниже медианы, см.
# UNDERPRICED_THRESHOLD) дублируются в @perekyp_vrn, только если скидка ещё
# больше — так канал служит наглядной витриной того, что видят платные
# подписчики основных каналов. Публикует и этот проект, и 500k-1.5М-версия —
# в один и тот же канал, поэтому там видно находки из обоих сегментов.
PEREKUP_CHAT_ID = os.environ.get("PEREKUP_CHAT_ID", "")
PEREKUP_BOT_LINK = "https://t.me/Python_DS_bot"  # воронка: выбор канала -> оплата -> доступ
PEREKUP_DISCOUNT_THRESHOLD = 0.50  # дублируем, если цена <= 50% медианы группы
PEREKUP_SEGMENT_LABEL = "50к–500к"

# --- Файлы состояния (создаются автоматически) ---
DATA_DIR = os.path.join(os.path.dirname(__file__), "data")
PRICE_HISTORY_FILE = os.path.join(DATA_DIR, "price_history.json")
POSTED_FILE = os.path.join(DATA_DIR, "posted.json")

# --- Вежливость к площадке ---
MIN_DELAY_BETWEEN_REQUESTS_SEC = 4   # пауза между запросами внутри одного прогона
MAX_PAGES_PER_RUN = 15               # на диапазон 50-500к объявлений может быть ещё больше, чем на основном канале
REQUEST_TIMEOUT_MS = 45_000          # у Drom бывают медленные ответы (замечено ~19-30с)
PAGE_LOAD_RETRIES = 1                # сколько раз повторить загрузку страницы при таймауте
